    <h2><span class="sec-no">肆</span>严格定义</h2>
    <div class="definition">
      <div class="def-title">📐 定义（古典概率，拉普拉斯 1812 定型）</div>
      <p>
        设试验的所有可能结果构成有限集 <MathInline tex="\Omega = \{\omega_1, \dots, \omega_n\}" />（样本空间），
        且各结果<strong>等可能</strong>。事件 A 是 Ω 的子集，其概率定义为
      </p>
      <MathBlock tex="P(A) = \frac{|A|}{|\Omega|} = \frac{\text{A 包含的基本结局数}}{\text{全部基本结局数}}" />
    </div>
    <p>逐词拆解，每个成分都在防一个历史陷阱：</p>
    <ul>
      <li>
        <strong>样本空间 Ω 要先摆出来</strong>——概率永远是"相对于哪一份完整清单"而言的。
        帕乔利们吵不出结果，就是因为谁也没把清单列全；
      </li>
      <li>
        <strong>"等可能"写在前提里，不在结论里</strong>——它是这个定义的适用条件，不是它能证明的东西。
        达朗贝尔的 1/3 错在清单没拆到底，混进了"粗细不均"的结局；
      </li>
      <li>
        <strong>事件 = 子集</strong>——这个不起眼的选择意义深远：事件的"或、且、非"变成了集合的并、交、补，
        概率的运算从此有语法可依。1933 年柯尔莫哥洛夫的公理化（第三讲细说）保留的正是这套骨架，
        只是把"数个数"换成了更一般的"量长度"。
      </li>
    </ul>

    <h2><span class="sec-no">伍</span>买到了什么：从赌桌到整个不确定世界</h2>

    <h3>看球时屏幕角上那个胜率：三百七十年前那道题还在跑</h3>
    <p>
      看比赛时，屏幕角上常挂着一个实时更新的数字："主队胜率 68%"。
      它算的<strong>就是</strong>这一讲的题目：比赛还没打完，
      把接下来所有可能的走向列出来，数一数（或加权算一下）对某一方有利的占几分之几。
      三百七十年前帕斯卡替一场散场的赌局分钱用的办法，今天每秒钟在服务器上跑几百万次。
    </p>
    <p>
      <strong>而它顺手回答了一个体育迷都有的疑问：为什么大赛都要打多局？</strong>
      直觉说"多打几场更能看出真实水平"，但到底能看出多少，是可以算的。
      把上面那个公式里的"每局各占一半"放松成"甲每局胜率 p"，
      甲赢下"先胜 N 局"这个赛制的概率就是
    </p>
    <MathBlock tex="P = \sum_{k=N}^{2N-1} \binom{2N-1}{k}\, p^k (1-p)^{\,2N-1-k}" />
    <p>
      （还是费马那一招：假想把 <MathInline tex="2N-1" /> 局全部打完。）代几个数进去：
    </p>
    <MathBlock tex="\begin{array}{c|ccc} \text{赛制} & p = 0.51 & p = 0.55 & p = 0.60 \\ \hline \text{一局定胜负} & 51.0\% & 55.0\% & 60.0\% \\ \text{三局两胜} & 51.9\% & 59.3\% & 68.3\% \\ \text{七局四胜} & 52.2\% & 60.8\% & 71.0\% \\ \text{二十一局十一胜} & 53.7\% & 67.9\% & 82.6\% \end{array}" />
    <p>
      <strong>赛制是一台放大器</strong>：实力只强 5%（每局 55%）的一方，
      一局定胜负时赢面 55%，打成十一胜制就变成 68%。
      局数越多，运气被摊得越平，实力差被放得越大。
      所以世界杯决赛不用点球直接开始，NBA 季后赛越往后场次越多，
      而"爆冷"几乎只发生在单场淘汰赛里——<strong>赛制设计本质上是在选择让多少运气留在场上</strong>。
      顺带也解释了为什么弱队宁可"赌一把"：缩短赛制是他们唯一能做的事。
    </p>
    <div class="insight">
      <div class="insight-title">💡 层层放大：网球每分只强 5%，整场胜率 95%</div>
      <p>
        网球把这台放大器<strong>套了四层</strong>：分 → 局 → 盘 → 场，
        每一层都是一个"先到 N 且领先 2"的小赛制。
        假设某位选手每一分的胜率是 p（且各分独立），一层层算上去：
      </p>
      <MathBlock tex="\begin{array}{c|cccc} \text{每分} & \text{每局} & \text{每盘} & \text{三盘两胜} & \text{五盘三胜} \\ \hline 51\% & 52.5\% & 57.1\% & 60.6\% & 63.2\% \\ 53\% & 57.5\% & 70.5\% & 79.0\% & 84.3\% \\ 55\% & 62.3\% & 81.5\% & 91.0\% & 95.3\% \\ 60\% & 73.6\% & 96.3\% & 99.6\% & \approx 100\% \end{array}" />
      <p>
        <strong>每一分只赢 55%，五盘三胜的整场胜率是 95.3%。</strong>
        这个数字解释了一件看球时的常见错觉：顶尖选手打起来像是碾压，
        比分动辄 6:2、6:1，让人以为双方实力天差地别；
        可拆到每一分，强的那位<strong>也不过是十一分里多赢一分</strong>。
        <strong>你在电视上看到的悬殊，是赛制把一个微小优势放大了四轮之后的样子。</strong>
      </p>
      <p>
        （这张表可以自查：把 p 设成 50%，四列会<strong>全都是 50%</strong>——
        势均力敌时无论套多少层赛制都还是五五开，放大器不会凭空造出优势。
        这既是算法的自检，也说明了放大器的性质：它放大差距，但不制造差距。）
      </p>
      <p>
        <strong>代价也要说清：这张表建立在"每一分独立、且概率恒定"之上，而真实比赛不是。</strong>
        发球方本来就占优（职业男子网球发球局得分率约六成，接发球局约四成），
        所以真实模型必须给两种情形各估一个 p；
        再加上体力衰减、心理波动、连得数分后的势头——这些都让"独立"打折扣。
        所以直播里那个胜率并不是拿一个 p 算出来的，
        而是用历史数据分别估计各种局面下的胜率再拼起来。
        <strong>但骨架仍然是费马那一句：列出未来的所有走向，算一算你占几分之几。</strong>
      </p>
    </div>

    <h3>还买到了什么</h3>
    <ul>
      <li>
        <strong>组合计数成了概率的算术</strong>：数结局要用排列组合，帕斯卡三角、二项式系数从此和概率结缘——
        <router-link to="/probability/clt">第 5 讲</router-link>棣莫弗逼近二项系数时，
        会顺手撞见正态分布；上面那张赛制表用的正是同一个 <MathInline tex="\binom{n}{k}" />；
      </li>
      <li>
        <strong>期望的种子已经种下</strong>："赌注的公平份额"推广开就是"随机收益的公平价格"，
        惠更斯 1657 年写进了第一本概率教科书。保险、年金、彩票定价，全是点数分配问题换了行头——
        <router-link to="/probability/lln">第 4 讲</router-link>会说清这个"公平价格"
        凭什么在长期真的兑现；
      </li>
      <li>
        <strong>方法论的胜利</strong>：费马"列举未来"的思路，就是今天算法里的穷举法与决策树；
        帕斯卡"逐局面倒推价值"的递推法，正是<strong>动态规划</strong>的雏形——
        上面那个折叠框里已经用它算过一遍 3/4 了。
      </li>
    </ul>
