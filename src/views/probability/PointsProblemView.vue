    <h2><span class="sec-no">贰</span>破局：别数过去，数未来的等可能结局</h2>
    <p>思想转折就一句话，但它值一整门学科：</p>
    <div class="insight">
      <div class="insight-title">💡 核心直觉：赢面 = 有利结局占等可能结局的比例</div>
      <p>
        "运气"没法度量，但<strong>结局可以数</strong>。把未来拆成若干个"机会均等"的基本结局，
        对你有利的占几分之几，你的赢面就是几分之几——这个比例，后人称之为<strong>概率</strong>。
        赌注按赢面分配，双方都无话可说：这不是和稀泥，是数出来的公平。
      </p>
    </div>
    <p>
      注意这一步悄悄完成的观念革命：在此之前，未来是神明的领地，骰子是占卜的工具；
      在此之后，<strong>不确定性本身成了可以计算的对象</strong>。伽利略的同代人算过几个骰子问题，
      但把"未来的可能性"当成一个可交易、可分割的量（赌注的公平份额），是 1654 年的全新发明——
      三年后惠更斯把它命名为"赌局的价值"，那就是<strong>期望</strong>的前身（第四讲的主角）。
    </p>
    <p>
      不过这一讲从开头到现在，那个 <strong>3:1</strong> 一直是被<strong>宣布</strong>的，没被<strong>算</strong>过。
      它是全讲的立论，值得当场算一遍——而且真正精彩的不是那四行加减，
      是费马为了让"等可能"成立而做的一个<strong>看起来多此一举的动作</strong>：
    </p>
    <RevealBox
      title="🔍 费马怎么算出 3:1，以及他为什么要把已经结束的比赛接着赌完"
      label="对答案 / 看完整拆解"
    >
      <template #hint>
        先自己动笔：甲 2:1 领先、先胜 3 局者胜。所以<strong>甲还需 1 胜，乙还需 2 胜</strong>。
        把接下来可能发生的事列个清单，数一数甲赢的占几分之几。
        （做完先别急着看答案——检查一下你列的那些结局，
        真的<strong>两两机会均等</strong>吗？这才是这道题的机关。）
      </template>
      <p>
        <strong>第一步：先看一个错误的列法</strong>，因为大多数人第一次都会这么列。
        "赌到分出胜负就停"，于是清单是：
      </p>
      <MathBlock tex="\text{甲} \ ;\quad \text{乙甲} \ ;\quad \text{乙乙}" />
      <p>
        三种结局，甲赢两种——难道是 2:1？<strong>错。</strong>这三条路<strong>长短不一</strong>：
        第一条只赌 1 局，后两条赌了 2 局。第一条发生的机会是 1/2，
        后两条各是 1/4。<strong>清单里的项不等可能，就不能直接数个数</strong>——
        这跟贰节末尾达朗贝尔栽的跟头是同一个坑，只是换了张脸。
      </p>
      <p>
        <strong>第二步：费马的动作——把剩下的局<strong>补齐</strong>赌完。</strong>
        甲需 1 胜、乙需 2 胜，那么<strong>最多再赌 2 局必定分出胜负</strong>
        （赌满 2 局后，甲至少赢 1 局或乙赢满 2 局，二者必居其一）。
        于是干脆<strong>假装两局都赌完</strong>，哪怕胜负早已分晓也照赌不误。
        这样每条路都恰好 2 局，长度一致，四种结局<strong>货真价实地等可能</strong>：
      </p>
      <MathBlock tex="\text{甲甲} \ ;\quad \text{甲乙} \ ;\quad \text{乙甲} \ ;\quad \text{乙乙}" />
      <p>
        <strong>第三步：数。</strong>甲只要在这两局里赢到<strong>至少一局</strong>就拿下整个赌局，
        所以前三条都是甲赢，只有"乙乙"才是乙赢：
      </p>
      <MathBlock tex="P(\text{甲胜}) = \frac{3}{4}, \qquad P(\text{乙胜}) = \frac{1}{4} \quad\Longrightarrow\quad \text{赌注按 } 3:1 \text{ 分}" />
      <p>
        <strong>"多赌的那几局"要紧在哪儿？</strong>它们对结果<strong>毫无影响</strong>——
        甲第一局就赢了的话，第二局赌不赌都改变不了他已经赢了这个事实。
        费马添上它们，纯粹是为了<strong>把所有路径修剪成同样长</strong>，
        好让"数个数"这个动作合法。
        <strong>这是概率论第一个真正的技巧：为了让结局等可能，可以往清单里塞进不影响结果的事件。</strong>
        （帕斯卡在信里专门为这一点跟费马争论过，他起初觉得"赌已经结束的局"荒谬。）
      </p>
      <p>
        <strong>第四步：一般情形。</strong>甲还需 a 胜、乙还需 b 胜时，
        最多再赌 <MathInline tex="a + b - 1" /> 局，共
        <MathInline tex="2^{a+b-1}" /> 条等长路径，甲赢的是"其中至少 a 局归甲"的那些：
      </p>
      <MathBlock tex="P(\text{甲胜}) = \frac{1}{2^{\,a+b-1}} \sum_{k=a}^{a+b-1} \binom{a+b-1}{k}" />
      <p>
        组合数就这样第一次走进了概率论。
        上面的动画就是这个公式的可视化——拖两根滑杆，
        它把整棵树画出来并替你数红色叶子。
        <strong>而帕斯卡走的是另一条路</strong>：他不列举，而是<strong>从终局往回倒推</strong>——
        任一局面的价值 = 下一局两种走向的价值的平均。
        比如"甲还需 1、乙还需 1"的价值显然是 1/2，
        由此倒推"甲还需 1、乙还需 2"= <MathInline tex="\tfrac12(1 + \tfrac12) = \tfrac34" />，
        同样得到 3:1。<strong>这套"倒推价值"的写法，就是今天动态规划的原型</strong>，
        而费马那套"列举全部路径"则是穷举与决策树的原型。
        同一道分赌注的题，两百年后长成了算法课的两章。
      </p>
    </RevealBox>
    <p>
      但"等可能"三个字是滑铁卢多发地段。大数学家<strong>达朗贝尔</strong>后来在百科全书里翻车：
      掷两枚硬币，结果不是"两正、两反、一正一反"三种吗？所以各占 1/3？——错。
      "一正一反"其实是两种结局（甲正乙反、甲反乙正）合并的，真概率是 2/4。
      <strong>等可能不能拍脑袋认定，要拆到不能再拆的基本结局才算数。</strong>下面亲手数一次。
    </p>

